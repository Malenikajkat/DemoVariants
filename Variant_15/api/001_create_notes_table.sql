-- Если таблица уже существует — удаляем её (CASCADE удалит и зависимости)
-- Это удобно для тестирования, но в продакшене используйте с осторожностью!
DROP TABLE IF EXISTS notes CASCADE;

-- Создаём таблицу notes со следующей структурой:
CREATE TABLE notes (
    id SERIAL PRIMARY KEY,           -- Уникальный идентификатор заметки (автоинкремент)
    title VARCHAR(255) NOT NULL,     -- Заголовок заметки (обязательное поле, до 255 символов)
    content TEXT,                    -- Содержание заметки (текст любой длины)
    id_user INTEGER NOT NULL,        -- Код пользователя, которому принадлежит заметка
    created_at TIMESTAMP DEFAULT NOW() -- Дата и время создания (по умолчанию — сейчас)
);

