JSON_FILE = Path(__file__).parent / "Заказчики.json"

# ==================== ФУНКЦИЯ load_json ====================
def load_json(filepath: Path) -> list:
    """
    Загружает данные из JSON-файла.
    
    Аргументы:
        filepath — путь к JSON-файлу (например: "C:/task2_db/Заказчики.json")
    
    Возвращает:
        Список словарей с данными клиентов
    
    Пример:
        # Представьте, что в JSON-файле написано:
        # [
        #   {"name": "ООО \"Ромашка\"", "inn": "1234567890", ...},
        #   {"name": "ИП Иванов", "inn": "", ...}
        # ]
        
        # После вызова load_json мы получим:
        # [
        #   {"name": "ООО \"Ромашка\"", "inn": "1234567890", ...},
        #   {"name": "ИП Иванов", "inn": "", ...}
        # ]
    
    Что такое JSON?
    ----------------
    JSON (JavaScript Object Notation) — это формат для хранения данных.
    Представьте, что это текст, но структурированный.
    
    Пример JSON:
    {
        "name": "ООО \"Ромашка\"",
        "inn": "1234567890",
        "address": "г. Москва"
    }
    
    Это похоже на словарь в Python:
    {
        "name": "ООО \"Ромашка\"",
        "inn": "1234567890",
        "address": "г. Москва"
    }
    """
    # Проверяем, существует ли файл
    if not filepath.exists():
        # Если файла нет — выбрасываем ошибку
        raise FileNotFoundError(f"Файл не найден: {filepath}")
    
    # Открываем файл и читаем его содержимое
    # with open(...) — это безопасный способ открыть файл
    # "r" — режим чтения (read)
    # encoding="utf-8" — кодировка (чтобы работали русские буквы)
    with open(filepath, "r", encoding="utf-8") as f:
        # json.load() — это функция, которая читает JSON из файла
        # и превращает его в Python-объект
        data = json.load(f)
    
    # Проверяем, что данные — это список
    # isinstance(data, list) — это проверка: "data является списком?"
    if not isinstance(data, list):
        # Если данные не список — выбрасываем ошибку
        raise ValueError("JSON-файл должен содержать массив объектов")
    
    # Возвращаем данные
    return data

# ==================== ФУНКЦИЯ import_customers ====================
def import_customers(customers: list) -> None:
    """
    Импортирует данные клиентов в таблицу customer базы данных.
    
    Аргументы:
        customers — список словарей с данными клиентов
                   (например: [{"name": "ООО \"Ромашка\"", "inn": "1234567890", ...}, ...])
    
    Что делает эта функция?
    ------------------------
    1. Подключается к базе данных
    2. Очищает таблицу customer (удаляет старые данные)
    3. Добавляет новых клиентов из списка customers
    4. Показывает результат
    
    Как это работает?
    -----------------
    1. psycopg2.connect() — создаёт соединение с базой данных
    2. conn.cursor() — создаёт курсор (это как ручка, которой мы пишем в базе)
    3. cursor.execute() — выполняет SQL-запрос
    4. conn.commit() — сохраняет изменения в базе
    """
    conn = None  # Переменная для хранения соединения с базой данных
    
    try:
        # ==================== ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ ====================
        # psycopg2.connect() — подключается к базе данных
        # **DB_CONFIG — это распаковка словаря
        # Вместо {"host": "localhost", "port": 5432, ...}
        # Мы передаём host="localhost", port=5432, ...
        print(f"Подключение к базе данных '{DB_CONFIG['database']}' на {DB_CONFIG['host']}:{DB_CONFIG['port']}...")
        conn = psycopg2.connect(**DB_CONFIG)
        
        # cursor() — создаёт курсор
        # Курсор — это объект, который выполняет SQL-запросы
        cursor = conn.cursor()
        
        print(f"Подключение успешно!\n")
        
        # ==================== ОЧИСТКА ТАБЛИЦЫ ====================
        # DELETE FROM customer — удаляет все записи из таблицы customer
        # conn.commit() — сохраняет изменения
        print("Очистка таблицы customer...")
        cursor.execute("DELETE FROM customer")
        conn.commit()
        print("Таблица очищена.\n")
        
        # ==================== ИМПОРТ ДАННЫХ ====================
        success_count = 0  # Счётчик успешных импортов
        error_count = 0    # Счётчик ошибок
        
        # for customer in customers — это цикл
        # Он проходит по каждому клиенту в списке
        for customer in customers:
            try:
                # Извлекаем данные из словаря
                # .get("name", "") — получает значение по ключу "name"
                # Если ключа нет — возвращает "" (пустую строку)
                # .strip() — удаляет пробелы в начале и конце
                name = customer.get("name", "").strip()
                
                # Проверяем, что имя не пустое
                if not name:
                    print(f"  ⚠ Пропуск: отсутствует 'name' для id={customer.get('id')}")
                    error_count += 1
                    continue  # Переходим к следующему клиенту
                
                # Извлекаем остальные поля
                # or None — если строка пустая, заменяем на None (NULL в базе данных)
                inn = customer.get("inn", "").strip() or None
                address = customer.get("addres", "").strip() or None  # Опечатка в JSON сохранена
                phone = customer.get("phone", "").strip() or None
                customer_type = customer.get("type", "").strip()
                
                # Проверка типа клиента
                if customer_type not in ("Поставщик", "Покупатель"):
                    print(f"  ⚠ Пропуск: неверный тип '{customer_type}' для id={customer.get('id')}")
                    error_count += 1
                    continue
                
                # ==================== ВСТАВКА В БАЗУ ДАННЫХ ====================
                # SQL-запрос для вставки данных
                # %s — это место, куда подставятся значения
                # psycopg2 автоматически экранирует значения (защита от SQL-инъекций)
                insert_query = """
                    INSERT INTO customer (name, inn, address, phone, customer_type)
                    VALUES (%s, %s, %s, %s, %s)
                    RETURNING id
                """
                
                # cursor.execute() — выполняет SQL-запрос
                # (name, inn, address, phone, customer_type) — это кортеж со значениями
                cursor.execute(insert_query, (name, inn, address, phone, customer_type))
                
                # cursor.fetchone() — получает одну запись из результата
                # [0] — берём первое значение (id)
                new_id = cursor.fetchone()[0]
                
                print(f"  ✓ Импортирован: {name} (id={new_id}, type={customer_type})")
                success_count += 1
                
            except Exception as e:
                # Если произошла ошибка — показываем сообщение
                print(f"  ✗ Ошибка импорта для {customer.get('id', '?')}: {e}")
                error_count += 1
                continue
        
        # Сохраняем все изменения в базе данных
        conn.commit()
        
        # ==================== ПОКАЗЫВАЕМ РЕЗУЛЬТАТ ====================
        print(f"\n{'='*60}")
        print(f"ИМПОРТ ЗАВЕРШЕН")
        print(f"  Успешно импортировано: {success_count}")
        print(f"  Ошибок: {error_count}")
        print(f"  Всего обработано: {len(customers)}")
        print(f"{'='*60}\n")
        
        # ==================== ВЫВОДИМ ДАННЫЕ ИЗ БАЗЫ ====================
        print("Текущее содержимое таблицы customer:")
        print("-" * 60)
        
        # SELECT — это запрос на выборку данных
        # FROM customer — из таблицы customer
        # ORDER BY id — упорядочить по id
        cursor.execute("SELECT id, name, inn, address, phone, customer_type FROM customer ORDER BY id")
        rows = cursor.fetchall()  # Получаем все строки
        
        # Форматируем вывод
        # f"{'ID':<5}" — это форматирование строки
        # <5 — выравнивание по левому краю, ширина 5 символов
        print(f"{'ID':<5} {'Название':<30} {'ИНН':<15} {'Тип':<12} {'Телефон'}")
        print("-" * 60)
        
        # row[0] — первое значение (id)
        # row[1] — второе значение (name)
        # row[2] — третье значение (inn)
        # row[4] — пятое значение (phone)
        # row[5] — шестое значение (customer_type)
        for row in rows:
            print(f"{row[0]:<5} {row[1]:<30} {str(row[2] or ''):<15} {row[5]:<12} {row[4] or ''}")
        print("-" * 60)
        
    # ==================== ОБРАБОТКА ОШИБОК ====================
    except psycopg2.OperationalError as e:
        # Ошибка подключения к базе данных
        print(f"✗ Ошибка подключения к базе данных: {e}")
        print("Убедитесь, что PostgreSQL запущен и база данных создана.")
        sys.exit(1)
    
    except FileNotFoundError as e:
        # Файл не найден
        print(f"✗ {e}")
        sys.exit(1)
    
    except json.JSONDecodeError as e:
        # Ошибка чтения JSON
        print(f"✗ Ошибка парсинга JSON: {e}")
        sys.exit(1)
    
    except Exception as e:
        # Любая другая ошибка
        print(f"✗ Неожиданная ошибка: {e}")
        sys.exit(1)
    
    finally:
        # finally — это блок, который выполняется ВСЕГДА
        # Даже если произошла ошибка
        if conn:
            conn.close()  # Закрываем соединение с базой данных
            print("Соединение с БД закрыто.")

# ==================== ФУНКЦИЯ create_sample_users ====================
def create_sample_users(cursor, conn) -> None:
    """
    Создаёт тестовых пользователей для авторизации.
    
    Аргументы:
        cursor — курсор базы данных
        conn — соединение с базой данных
    
    Что делает эта функция?
    ------------------------
    Создаёт 3 тестовых пользователя:
    1. admin (администратор)
    2. user1 (пользователь)
    3. user2 (пользователь)
    
    Зачем это нужно?
    -----------------
    Чтобы можно было протестировать систему авторизации.
    """
    print("\nСоздание тестовых пользователей...")
    
    # Список пользователей: (login, password, role)
    users = [
        ("admin", "admin123", "Администратор"),
        ("user1", "user123", "Пользователь"),
        ("user2", "user123", "Пользователь"),
    ]
    
    # Проходим по каждому пользователю
    for login, password_hash, role in users:
        try:
            # SQL-запрос для вставки пользователя
            # ON CONFLICT (login) DO NOTHING — если пользователь с таким логином уже существует,
            # ничего не делать (не создавать ошибку)
            cursor.execute("""
                INSERT INTO user_account (login, password_hash, role, is_blocked)
                VALUES (%s, %s, %s, FALSE)
                ON CONFLICT (login) DO NOTHING
            """, (login, password_hash, role))
            
            print(f"  ✓ Пользователь '{login}' ({role})")
        except Exception as e:
            print(f"  ✗ Ошибка создания '{login}': {e}")
    
    # Сохраняем изменения
    conn.commit()
    print("Готово!\n")

